export type MessageKey = keyof typeof messages;
export function useI18n() {
  const { store } = useStore();
  const language = store.settings.language;
  const index = { en: 0, es: 1, ru: 2, tr: 3 }[language];
  return {
    language,
    t: (key: MessageKey) => messages[key][index],
    loc: (value: Localized) => value[language],
    date: (value: string) =>
      new Intl.DateTimeFormat(language, {
        day: "numeric",
        month: "short",
      }).format(new Date(value + "T12:00:00")),
  };
}
export function variantKey(value: string): MessageKey {
  return value in messages ? (value as MessageKey) : "standard";
}
